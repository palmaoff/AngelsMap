  // векторы через SVG, тайлы догружает во время панорамирования, а кластеры
  // анимирует при зуме) и при необходимости откатить одним значением.
  // См. использование в js/map.js (init()).
  //
  // ИТОГ ЗАМЕРОВ (live, localhost/map, зум-стресс на ДТП+АдминистративныеЕдиницы):
