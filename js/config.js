// Тестовый override флагов производительности через URL-параметры — чтобы
// сравнивать комбинации простой перезагрузкой страницы, не редактируя файл
// (canvas/SVG и padding задаются при создании L.map и живьём не меняются).
// Ключи: pc=preferCanvas, uwi=tilesUpdateWhenIdle, uwz=tilesUpdateWhenZooming,
// vtl=vectorTilesLines, vtp=vectorTilesPolygons, fa=fadeAnimation (все булевы:
// 1/0/true/false), pad=rendererPadding (число).
// Пример: ?pc=1&pad=0.5&uwz=1  → как было до правок (canvas, padding 0.5,
// тайлы грузятся во время зума); ?vtl=1&vtp=0 → векторные тайлы для линий,
// классический рендер для полигонов. Ничего не задано — берутся значения выше.
(function applyPerfOverrides() {
  const q = new URLSearchParams(location.search);
  if (![...q.keys()].length) return;
  const bool = (k, prop) => { if (q.has(k)) MapConfig.perf[prop] = /^(1|true|yes)$/i.test(q.get(k)); };
  bool('pc',  'preferCanvas');
  bool('uwi', 'tilesUpdateWhenIdle');
  bool('uwz', 'tilesUpdateWhenZooming');
  bool('vtl', 'vectorTilesLines');
  bool('vtp', 'vectorTilesPolygons');
  bool('fa',  'fadeAnimation');
  if (q.has('pad')) { const n = parseFloat(q.get('pad')); if (!isNaN(n)) MapConfig.perf.rendererPadding = n; }
  console.log('[MapConfig] perf overrides применены:', JSON.stringify(MapConfig.perf));
})();

window.MapConfig = MapConfig;
